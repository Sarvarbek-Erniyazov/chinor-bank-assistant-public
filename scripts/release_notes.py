"""docs/release_notes_<version>.md from the CHANGELOG section of that version (nothing typed here but the headings).

python scripts/release_notes.py v1.2.0 [--previous v1.1.1] [--check]

New: every bullet of the section except "Correction" and "Pending" bullets. Changed: the "Correction" bullets.
Pending: the "Pending" bullet. Numbers of the previous release: computed here. Every numeric token of the previous
release's result files (results/*.md and *.csv outside results/runs and results/raw, figures/T*.md, docs/claims.md,
docs/figures.md, docs/limitations.md, eval/contamination_report.md) must still occur at least as often in HEAD;
dates (YYYY-MM-DD) are not results and are skipped. Files where a number no longer occurs are listed.
--check: exit 1 if the committed notes differ from a fresh build (no writing).
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NUM = re.compile(r"(?<![\w.])[-+−]?\d[\d,]*(?:\.\d+)?%?")
DATE = re.compile(r"\b\d{4}-\d{2}-\d{2}\b")


def git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True)


def section(version: str) -> list[str]:
    text = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
    m = re.search(rf"^## {re.escape(version)}\b.*?$\n(.*?)(?=^## |\Z)", text, re.S | re.M)
    if not m:
        raise SystemExit(f"no CHANGELOG section for {version}")
    bullets, cur = [], None
    for line in m.group(1).splitlines():
        if line.startswith("- "):
            cur = line[2:]
            bullets.append(cur)
        elif line.startswith("  ") and bullets:
            bullets[-1] += " " + line.strip()
    return bullets


def result_files(ref: str) -> list[str]:
    files = git("ls-tree", "-r", "--name-only", ref).stdout.decode().split()
    return [f for f in files if (f.startswith("results/") and f.endswith((".md", ".csv")) and "/runs/" not in f
                                 and "/raw/" not in f) or re.fullmatch(r"figures/T\d+\.md", f)
            or f in ("docs/claims.md", "docs/figures.md", "docs/limitations.md", "eval/contamination_report.md")]


def numbers_kept(previous: str) -> tuple[int, list[str]]:
    lost = []
    files = result_files(previous)
    for f in files:
        old = git("show", f"{previous}:{f}").stdout.decode("utf-8", "replace")
        new = git("show", f"HEAD:{f}")
        if new.returncode:
            lost.append(f"{f} (removed)")
            continue
        ca = Counter(NUM.findall(DATE.sub(" ", old)))
        cb = Counter(NUM.findall(DATE.sub(" ", new.stdout.decode("utf-8", "replace"))))
        miss = [k for k in ca if ca[k] > cb[k]]
        if miss:
            lost.append(f"{f}: {', '.join(miss[:8])}")
    return len(files), lost


def build(version: str, previous: str) -> str:
    bullets = section(version)
    pending = [b for b in bullets if b.startswith("**Pending.**")]
    changed = [b for b in bullets if "Correction" in b[:40]]
    new = [b for b in bullets if b not in pending and b not in changed]
    n, lost = numbers_kept(previous)
    L = [f"# Chinor Bank Assistant {version}", "",
         f"Generated by `scripts/release_notes.py` from the `{version}` section of [CHANGELOG.md](../CHANGELOG.md). "
         "Chinor Bank is fictional.", "", "## New", ""]
    L += [f"- {b}" for b in new]
    L += ["", "## Changed", ""] + ([f"- {b}" for b in changed] or ["- None."])
    L += ["", "## Pending", ""] + ([f"- {b.replace('**Pending.** ', '')}" for b in pending] or ["- None."])
    L += ["", f"## Numbers of {previous}", ""]
    if lost:
        L += [f"Checked {n} result files of {previous}: some numbers no longer occur in this release:", ""]
        L += [f"- {x}" for x in lost]
    else:
        L += [f"Every number in the {n} result files of {previous} (tables, figures index, claims, limitations; dates "
              "of regeneration excepted) still occurs in this release: the recorded numbers are unchanged, and this "
              "release only adds."]
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("version")
    ap.add_argument("--previous", default="v1.1.1")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    out = ROOT / "docs" / f"release_notes_{a.version}.md"
    text = build(a.version, a.previous)
    if a.check:
        ok = out.exists() and out.read_text(encoding="utf-8") == text
        print("ok" if ok else f"{out.relative_to(ROOT)} differs from a fresh build")
        sys.exit(0 if ok else 1)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
