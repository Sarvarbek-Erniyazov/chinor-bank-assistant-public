"""Pin the Qwen3 model revisions used by the recorded runs (docs/base_revisions.md).

python scripts/base_revisions.py [--out docs/base_revisions.md]
Collects every Qwen/* model id named in results/runs/*/train/run.json (config_values.model) and
eval/outputs/*/run.json (model), reads the current revision of each from the Hub (metadata only, anonymous: no token
is read or sent) and from the local Hugging Face cache when present (refs/main of the cached repo), and compares both
with the 8-character prefixes recorded in docs/tokenizer_notes.md ("Tied embeddings per Qwen3 base size", read from
the shared HF cache on 2026-10-29). No weights are downloaded. Exit code 1 if any recorded prefix does not match.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTES = ROOT / "docs" / "tokenizer_notes.md"


def used_ids() -> dict[str, set[str]]:
    """Qwen/* model id -> the kinds of run that name it (train / eval)."""
    ids: dict[str, set[str]] = {}
    for p in sorted((ROOT / "results" / "runs").glob("*/train/run.json")):
        m = (json.loads(p.read_text(encoding="utf-8")).get("config_values") or {}).get("model")
        if isinstance(m, str) and m.startswith("Qwen/"):
            ids.setdefault(m, set()).add("train")
    for p in sorted((ROOT / "eval" / "outputs").glob("*/run.json")):
        m = json.loads(p.read_text(encoding="utf-8")).get("model")
        if isinstance(m, str) and m.startswith("Qwen/"):
            ids.setdefault(m, set()).add("eval")
    return ids


def recorded_prefixes() -> dict[str, str]:
    """docs/tokenizer_notes.md table rows: | Qwen3-0.6B-Base | `da87bfb6` | ..."""
    out = {}
    for line in NOTES.read_text(encoding="utf-8").splitlines():
        m = re.match(r"\|\s*(Qwen3-[\w.-]+)\s*\|\s*`([0-9a-f]{8})`\s*\|", line)
        if m:
            out["Qwen/" + m.group(1)] = m.group(2)
    return out


def cached_revision(model_id: str) -> str | None:
    from huggingface_hub import constants
    ref = Path(constants.HF_HUB_CACHE) / ("models--" + model_id.replace("/", "--")) / "refs" / "main"
    return ref.read_text(encoding="utf-8").strip() if ref.exists() else None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "docs" / "base_revisions.md"))
    a = ap.parse_args()
    from huggingface_hub import HfApi
    api = HfApi()
    ids, prefixes = used_ids(), recorded_prefixes()
    today = date.today().isoformat()
    rows, bad = [], []
    for mid in sorted(ids):
        hub = api.model_info(mid, token=False).sha
        cache = cached_revision(mid)
        pre = prefixes.get(mid)
        if pre is None:
            match = "no prefix recorded"
        else:
            ok = hub.startswith(pre) and (cache is None or cache.startswith(pre))
            match = "yes" if ok else "NO"
            if not ok:
                bad.append(mid)
        cache_cell = "not cached" if cache is None else ("same as Hub" if cache == hub else f"`{cache}` (differs from Hub)")
        rows.append(f"| `{mid}` | {', '.join(sorted(ids[mid]))} | `{hub}` | {cache_cell} | "
                    f"{'`' + pre + '`' if pre else '—'} | {match} | {today} |")
    text = "\n".join([
        "# Base-model revisions",
        "",
        "Generated by `scripts/base_revisions.py`. Every recorded run.json has `revision: null`: the runs loaded the",
        "Hub's `main` at the time. The only revision record from the runs themselves is the 8-character prefixes in",
        "`docs/tokenizer_notes.md` (read from the shared HF cache on 2026-10-29). This table pins the full hashes and",
        "checks them against those prefixes. Hub = the repository's current `main` revision (metadata only); local",
        "cache = `refs/main` of the laptop's Hugging Face cache, where present. A match means the current revision",
        "begins with the recorded prefix; it does not prove the runs used that exact revision beyond what the prefix",
        "shows.",
        "",
        "| Model id | Used in | Full revision (Hub) | Local cache | Recorded prefix | Matches prefix | Date checked |",
        "|---|---|---|---|---|---|---|",
        *rows,
        "",
    ])
    Path(a.out).write_text(text, encoding="utf-8", newline="\n")
    print(text)
    if bad:
        print("PREFIX MISMATCH: " + ", ".join(bad), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
